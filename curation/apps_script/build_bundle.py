#!/usr/bin/env python3
# @title Bundle the MalAvi curation Apps Script files into one paste-ready file
# @purpose Concatenate the runtime .gs files of curation/apps_script/ into a single file,
#   so the live project can be updated with ONE paste instead of nine.
# @why Every Google-side change is a browser paste by the maintainer, and nine pastes are
#   nine chances to miss one (results/PLAN_SUBMISSION_SYSTEM_RETHINK_2026-10-14.md, F9).
#   Apps Script puts every file of a project in one global scope, so one file and nine
#   files behave identically; the split in the repository is for reading, not for Google.
# @input curation/apps_script/*.gs (the RUNTIME_FILES list below)
# @output curation/apps_script/dist/malavi_curation.gs
# @program python3
# @critical-var RUNTIME_FILES
"""Build curation/apps_script/dist/malavi_curation.gs.

    .venv/bin/python curation/apps_script/build_bundle.py            # write the bundle
    .venv/bin/python curation/apps_script/build_bundle.py --check    # is the bundle current?

The bundle holds the files a running project needs. The one-off builders
(create_submission_form.gs, create_verdict_form.gs, create_update_form.gs's builder half,
inspect_verdict_form.gs) are NOT bundled: they are pasted on the day they are needed and
removed afterwards. create_update_form.gs is bundled whole because its second half is the
update form's trigger handler.

The bundle refuses to build when two files declare the same top-level function: in one
project the last definition silently wins, which is how a renamed helper breaks a trigger
without an error.
"""
from __future__ import annotations

import re
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
DIST = HERE / "dist" / "malavi_curation.gs"

# Order is cosmetic (nothing runs at a file's top level); settings first for the reader.
RUNTIME_FILES = [
    "settings.gs",
    "mail.gs",            # the one place that sends; every other file calls it
    "status_sheet.gs",
    "publish_report.gs",
    "notify_on_submission.gs",
    "notify_on_verdict.gs",
    "create_update_form.gs",
    "inbox_triage.gs",
    "daily_clock.gs",
    "triggers.gs",
    "add_submitter_message_question.gs",
]

FUNCTION_RE = re.compile(r"^function\s+([A-Za-z_$][\w$]*)\s*\(", re.MULTILINE)


def duplicate_functions(sources: dict) -> dict:
    """function name -> the files that declare it, for names declared more than once."""
    seen: dict = {}
    for name, text in sources.items():
        for function in FUNCTION_RE.findall(text):
            seen.setdefault(function, []).append(name)
    return {function: files for function, files in seen.items() if len(files) > 1}


def review_status() -> str:
    """Whether the bundle on disk has an independent review on record (ops/record_review.py)."""
    try:
        import importlib.util
        path = HERE.parent.parent / "ops" / "record_review.py"
        spec = importlib.util.spec_from_file_location("_record_review", path)
        module = importlib.util.module_from_spec(spec)
        sys.modules["_record_review"] = module
        spec.loader.exec_module(module)
        if module.is_reviewed():
            return "REVIEWED: this bundle's hash is in curation/REVIEWS.md; it may be pasted."
        return ("NOT REVIEWED: this bundle's hash is not in curation/REVIEWS.md. Do not paste "
                "it into the live project until an independent review has been recorded "
                "(ops/record_review.py).")
    except Exception as exc:                                       # noqa: BLE001
        return f"review status unknown ({exc})"


def build() -> str:
    sources = {name: (HERE / name).read_text(encoding="utf-8") for name in RUNTIME_FILES}
    clashes = duplicate_functions(sources)
    if clashes:
        lines = [f"  {function}: {', '.join(files)}" for function, files in sorted(clashes.items())]
        raise SystemExit("Refusing to bundle: the same function is declared in more than one "
                         "file (the last one would silently win):\n" + "\n".join(lines))
    # The one-off builders are not bundled, but somebody may paste one into the live project
    # for a day. Say so if that would override a bundled function (review 2026-10-16, 16).
    builders = {path.name: path.read_text(encoding="utf-8")
                for path in HERE.glob("*.gs") if path.name not in RUNTIME_FILES}
    with_builders = duplicate_functions({**sources, **builders})
    for function, files in sorted(with_builders.items()):
        print(f"note: {function} is declared in {', '.join(files)}; pasting that builder into "
              f"the live project would override the bundled copy", file=sys.stderr)
    parts = ["// GENERATED by curation/apps_script/build_bundle.py from the files named below.\n"
             "// Do not edit here: edit the source file, rebuild, paste the whole thing over the\n"
             "// project's Code.gs. Files: " + ", ".join(RUNTIME_FILES) + "\n"]
    for name, text in sources.items():
        parts.append(f"\n\n// {'=' * 86}\n// FILE: {name}\n// {'=' * 86}\n\n{text.rstrip()}\n")
    return "".join(parts)


def main(argv=None) -> int:
    arguments = list(sys.argv[1:] if argv is None else argv)
    bundle = build()
    if "--check" in arguments:
        current = DIST.read_text(encoding="utf-8") if DIST.is_file() else ""
        if current == bundle:
            print(f"{DIST.relative_to(HERE.parent.parent)} is current.")
            return 0
        print(f"{DIST.relative_to(HERE.parent.parent)} is STALE: rebuild it.", file=sys.stderr)
        return 2
    DIST.parent.mkdir(parents=True, exist_ok=True)
    DIST.write_text(bundle, encoding="utf-8")
    print(f"wrote {DIST.relative_to(HERE.parent.parent)} ({len(bundle.splitlines())} lines, "
          f"{len(RUNTIME_FILES)} files)")
    print(review_status())
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
